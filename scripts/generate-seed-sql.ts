/**
 * Generates supabase/seed.sql from the same DEMO data the local backend uses.
 *
 *   npm run db:seed-sql
 *
 * Every row is inserted with is_demo = true so the website badges it as a demo
 * listing. Delete them before launch with:
 *   delete from public.properties where is_demo;
 */
import { writeFileSync } from "node:fs"
import path from "node:path"
import { buildSeedProperties } from "../src/lib/data/seed"

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null"
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null"
  if (typeof v === "boolean") return v ? "true" : "false"
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) return `array[${v.map(q).join(", ")}]::text[]`
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}

const lines: string[] = [
  "-- DEMO DATA. Generated by scripts/generate-seed-sql.ts — do not edit by hand.",
  "-- Not real Yaam listings. Remove before launch: delete from public.properties where is_demo;",
  "begin;",
]

for (const p of buildSeedProperties()) {
  const cols: Record<string, unknown> = {
    slug: p.slug,
    title: p.title,
    description: p.description,
    purpose: p.purpose,
    category: p.category,
    property_type: p.propertyType,
    price: p.price,
    price_label: p.priceLabel,
    negotiable: p.negotiable,
    address: p.address,
    locality: p.locality,
    city: p.city,
    state: p.state,
    pincode: p.pincode,
    latitude: p.latitude,
    longitude: p.longitude,
    location_precision: p.locationPrecision,
    area: p.area,
    area_unit: p.areaUnit,
    bedrooms: p.bedrooms,
    bathrooms: p.bathrooms,
    parking: p.parking,
    furnishing: p.furnishing,
    floor: p.floor,
    total_floors: p.totalFloors,
    facing: p.facing,
    construction_year: p.constructionYear,
    possession_status: p.possessionStatus,
    amenities: p.amenities,
    highlights: p.highlights,
    nearby_landmarks: p.nearbyLandmarks,
    custom_fields: p.customFields,
    cover_image_url: p.coverImageUrl,
    status: p.status,
    featured: p.featured,
    verified: p.verified,
    is_demo: true,
    created_at: p.createdAt,
  }
  const names = Object.keys(cols)
  const values = names.map((n) => {
    const v = cols[n]
    if (["purpose", "category", "property_type", "location_precision", "area_unit", "furnishing", "facing", "possession_status", "status"].includes(n) && v !== null) {
      return `${q(v)}::public.${n === "property_type" ? "property_type" : n === "purpose" ? "property_purpose" : n === "category" ? "property_category" : n === "status" ? "property_status" : n}`
    }
    if (n === "created_at") return `${q(v)}::timestamptz`
    if (n === "nearby_landmarks" || n === "custom_fields") return `${q(JSON.stringify(v))}::jsonb`
    return q(v)
  })
  const imgs = p.images
    .map((i) => `(${q(i.url)}, ${q(i.alt)}, ${q(i.width)}, ${q(i.height)}, ${i.position})`)
    .join(",\n    ")
  lines.push(
    "",
    `with p as (\n  insert into public.properties (${names.join(", ")})\n  values (${values.join(", ")})\n  on conflict (slug) do nothing\n  returning id\n)`,
    imgs
      ? `insert into public.property_images (property_id, url, alt, width, height, position)\nselect p.id, v.url, v.alt, v.width, v.height, v.position\nfrom p, (values\n    ${imgs}\n) as v(url, alt, width, height, position);`
      : "select 1 from p;",
  )
}
lines.push("", "commit;", "")

const out = path.join(process.cwd(), "supabase/seed.sql")
writeFileSync(out, lines.join("\n"))
console.log(`Wrote ${out}`)
