export function buildSeedProperties(now = new Date()): Property[] {
  return SEEDS.map((seed, index) => {
    const { photos, daysAgo, ...rest } = seed
    const input: PropertyInput = {
      ...EMPTY_PROPERTY_INPUT,
      status: "published",
      ...rest,
      images: photos.map((p, i) => img(p, `${seed.title} — photo ${i + 1}`, i)),
    }
    const created = new Date(now.getTime() - daysAgo * 86_400_000 - index * 60_000).toISOString()
    return {
      ...input,
      id: `demo-${String(index + 1).padStart(3, "0")}`,
      slug: buildPropertySlug(input),
      areaSqft: toSqft(input.area, input.areaUnit),
      coverImageUrl: input.images[0]?.url ?? null,
      isDemo: true,
      reviewNotes: null,
      createdAt: created,
      updatedAt: created,
      publishedAt: input.status === "draft" ? null : created,
      createdBy: null,
    }
  })
}
